def render_document(spec: DocSpec) -> str:
    """把 DocSpec 渲染成 markdown。段落内的 {fact_key} 替换成事实句子。"""
    lines = [f"# {spec.title}", ""]
    for para in spec.paragraphs:
        lines.append(para.format(**FACTS))
        lines.append("")
    return "\n".join(lines)


def all_fact_keys() -> list[str]:
    return list(FACTS)
