HEADER = "> 分类：{cat} · 更新：2025-12 · 性质：**示例语料（虚构数据，仅用于功能验证）**"


def render(cat: str, title: str, points, paras, rows) -> str:
    lines = [f"# {title}", "", HEADER.format(cat=cat), "", "## 要点", ""]
    lines += [f"- {p}" for p in points]
    lines += ["", "## 正文", ""]
    lines += list(paras)
    lines += ["", "## 关键数据", "", "| 指标 | 数值 | 口径说明 |", "|---|---|---|"]
    lines += [f"| {a} | {b} | {c} |" for a, b, c in rows]
    lines.append("")
    return "\n".join(lines)


